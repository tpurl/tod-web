/** Splits a glyph string into its 7 rows of 5 cells. */
export function glyphRows(glyph: string): string[] {
  const rows = glyph.split(' ');
  if (rows.length !== 7 || rows.some((r) => !/^[.#]{5}$/.test(r))) {
    throw new Error(`malformed glyph: ${glyph}`);
  }
  return rows;
}

/** Converts a 5x7 glyph to 8 pattern bytes (columns 1..5, rows 0..6). */
export function glyphToBytes(glyph: string): number[] {
  const bytes = glyphRows(glyph).map((row) => {
    let b = 0;
    for (let i = 0; i < 5; i++) if (row[i] === '#') b |= 0x80 >> (i + 1);
    return b;
  });
  bytes.push(0);
  return bytes;
}

/** Loads the font into pattern codes 32..95. */
export function loadFont(screen: TileScreen): void {
  GLYPHS.forEach((g, i) => screen.definePattern(FONT_FIRST + i, glyphToBytes(g)));
}
